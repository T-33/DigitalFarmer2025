"""
Language utilities for multilingual bot.
"""
from typing import Dict
from aiogram.fsm.context import FSMContext


async def get_user_language(state: FSMContext) -> str:
    """
    Get user's language preference from state.

    Args:
        state: FSM context

    Returns:
        str: Language code ('kg' or 'ru'), defaults to 'kg'
    """
    data = await state.get_data()
    return data.get("language", "kg")


async def set_user_language(state: FSMContext, lang: str):
    """
    Set user's language preference in state.

    Args:
        state: FSM context
        lang: Language code ('kg' or 'ru')
    """
    await state.update_data(language=lang)


def get_text(key: str, lang: str = "kg") -> str:
    """
    Get localized text by key.

    Args:
        key: Text key
        lang: Language code

    Returns:
        str: Localized text
    """
    texts = TEXTS.get(key, {})
    return texts.get(lang, texts.get("kg", ""))


